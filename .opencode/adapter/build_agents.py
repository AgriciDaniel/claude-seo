#!/usr/bin/env python3
"""Generate OpenCode subagent wrappers from the canonical claude-seo agents.

Each wrapper is a pointer: it carries native OpenCode V2 frontmatter and tells
the subagent to read the canonical prompt in ``agents/`` or
``extensions/*/agents/``. Canonical content is never copied, so an upstream body
edit needs no regeneration.

Usage:
    python3 .opencode/adapter/build_agents.py --write
    python3 .opencode/adapter/build_agents.py --check
    python3 .opencode/adapter/build_agents.py --check --json
"""

import argparse
import json
import re
import sys
from dataclasses import dataclass
from pathlib import Path

GENERATED_MARKER = "<!-- generated by .opencode/adapter/build_agents.py; do not edit -->"
ID_RE = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")

# Upstream Claude tool name -> OpenCode permission action.
TOOL_ACTIONS = {
    "Read": "read",
    "Bash": "shell",
    "Write": "edit",
    "Edit": "edit",
    "Glob": "glob",
    "Grep": "grep",
    "WebFetch": "webfetch",
    "WebSearch": "websearch",
}
# Allowed pass-through tools that the adapter does not map in v1.
IGNORED_TOOLS = ("mcp__dataforseo__*",)

# Action order in the generated permission list. "read" is handled separately
# because the .env rules must follow the broad read allow.
ACTION_ORDER = ("shell", "edit", "glob", "grep", "webfetch", "websearch")


@dataclass(frozen=True)
class AgentSource:
    id: str
    source: Path
    description: str
    max_turns: int
    tools: tuple[str, ...]


def split_frontmatter(text: str) -> tuple[str, str]:
    """Return (frontmatter, body) for a markdown file with YAML frontmatter."""
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        raise ValueError("missing opening frontmatter delimiter")
    for index in range(1, len(lines)):
        if lines[index].strip() == "---":
            return "\n".join(lines[1:index]), "\n".join(lines[index + 1 :])
    raise ValueError("missing closing frontmatter delimiter")


def _strip_inline_comment(value: str) -> str:
    if value.startswith(('"', "'")):
        quote = value[0]
        escaped = False
        for index in range(1, len(value)):
            char = value[index]
            if escaped:
                escaped = False
                continue
            if char == "\\" and quote == '"':
                escaped = True
                continue
            if char == quote:
                rest = value[index + 1 :]
                if rest.strip().startswith("#"):
                    return value[: index + 1]
                return value
        return value
    marker = value.find(" #")
    if marker >= 0:
        return value[:marker].rstrip()
    return value


def _decode_quoted(value: str) -> str:
    if value.startswith('"') and value.endswith('"') and len(value) >= 2:
        try:
            decoded = json.loads(value)
        except json.JSONDecodeError:
            decoded = value[1:-1].replace('\\"', '"').replace("\\\\", "\\")
        return decoded
    if value.startswith("'") and value.endswith("'") and len(value) >= 2:
        return value[1:-1].replace("''", "'")
    return value


def parse_frontmatter(frontmatter: str) -> dict[str, object]:
    """Parse the small YAML subset used by claude-seo agent frontmatter."""
    data: dict[str, object] = {}
    lines = frontmatter.splitlines()
    index = 0
    while index < len(lines):
        line = lines[index]
        if not line.strip() or line.lstrip().startswith("#"):
            index += 1
            continue
        if line.startswith((" ", "\t")):
            index += 1
            continue
        if ":" not in line:
            index += 1
            continue
        key, _, raw = line.partition(":")
        key = key.strip()
        value = raw.strip()
        if value in (">", "|", ">-", "|-", ">+", "|+"):
            block: list[str] = []
            index += 1
            while index < len(lines):
                candidate = lines[index]
                if candidate.strip() and not candidate.startswith((" ", "\t")):
                    break
                block.append(candidate.strip())
                index += 1
            data[key] = " ".join(part for part in block if part)
            continue
        if value == "":
            items: list[str] = []
            index += 1
            while index < len(lines):
                candidate = lines[index]
                stripped = candidate.strip()
                if stripped.startswith("- "):
                    items.append(_decode_quoted(_strip_inline_comment(stripped[2:].strip())))
                    index += 1
                    continue
                if stripped and not candidate.startswith((" ", "\t")):
                    break
                index += 1
            data[key] = items
            continue
        if value.startswith((">", "|")):
            # Block scalar with a chomping indicator followed by inline text is
            # not used by claude-seo; treat the remainder as a plain scalar.
            data[key] = _strip_inline_comment(value)
            index += 1
            continue
        value = _strip_inline_comment(value)
        data[key] = _decode_quoted(value)
        index += 1
    return data


def normalize_description(value: object) -> str:
    if not isinstance(value, str) or not value.strip():
        raise ValueError("missing description")
    description = re.sub(r"\s+", " ", value).strip()
    if any(ord(char) < 32 for char in description):
        raise ValueError("description contains control characters")
    return description


def parse_tools(value: object) -> tuple[str, ...]:
    if isinstance(value, list):
        raw = [str(item) for item in value]
    elif isinstance(value, str) and value.strip():
        raw = [part.strip() for part in value.split(",")]
    else:
        raise ValueError("missing tools")
    tools = tuple(part for part in raw if part)
    if not tools:
        raise ValueError("empty tools")
    for tool in tools:
        if tool in TOOL_ACTIONS or tool in IGNORED_TOOLS:
            continue
        raise ValueError(f"unknown tool: {tool}")
    if "Read" not in tools:
        raise ValueError("tools must include Read")
    return tools


def _read_agent(path: Path, root: Path) -> AgentSource:
    text = path.read_text(encoding="utf-8")
    frontmatter, _ = split_frontmatter(text)
    data = parse_frontmatter(frontmatter)
    agent_id = path.stem
    if not ID_RE.fullmatch(agent_id):
        raise ValueError(f"{path}: invalid agent id {agent_id!r}")
    try:
        description = normalize_description(data.get("description"))
        max_turns_raw = data.get("maxTurns")
        if not isinstance(max_turns_raw, str) or not re.fullmatch(r"\d+", max_turns_raw):
            raise ValueError("missing or non-integer maxTurns")
        max_turns = int(max_turns_raw)
        tools = parse_tools(data.get("tools"))
    except ValueError as exc:
        raise ValueError(f"{path}: {exc}") from exc
    return AgentSource(
        id=agent_id,
        source=path.relative_to(root),
        description=description,
        max_turns=max_turns,
        tools=tools,
    )


def discover_agents(root: Path) -> list[AgentSource]:
    """Return unique agent sources, core first, then extensions."""
    agents_dir = root / "agents"
    if not agents_dir.is_dir():
        raise ValueError(f"missing agent source directory: {agents_dir}")
    core_paths = sorted(agents_dir.glob("seo-*.md"), key=lambda path: path.name)
    if not core_paths:
        raise ValueError(f"no agent sources found under {agents_dir}")
    extension_paths = sorted(
        (root / "extensions").glob("*/agents/seo-*.md"), key=lambda path: path.as_posix()
    )
    agents: dict[str, AgentSource] = {}
    extension_owner: dict[str, Path] = {}
    for path in core_paths:
        agent = _read_agent(path, root)
        agents.setdefault(agent.id, agent)
    for path in extension_paths:
        agent = _read_agent(path, root)
        if agent.id in agents:
            if agent.id in extension_owner:
                raise ValueError(
                    f"duplicate extension agent {agent.id}: {extension_owner[agent.id]} and {path}"
                )
            continue
        agents[agent.id] = agent
        extension_owner[agent.id] = path
    return [agents[agent_id] for agent_id in sorted(agents)]


def _permission_line(action: str, resource: str, effect: str) -> str:
    return f'  - {{ action: {action}, resource: "{resource}", effect: {effect} }}'


def render_wrapper(agent: AgentSource) -> str:
    lines = [
        "---",
        f"description: {json.dumps(agent.description, ensure_ascii=False)}",
        "mode: subagent",
        f"steps: {agent.max_turns + 1}",
        "permissions:",
        '  - { action: "*", resource: "*", effect: deny }',
    ]
    actions = {TOOL_ACTIONS[tool] for tool in agent.tools if tool in TOOL_ACTIONS}
    if "read" in actions:
        lines.append(_permission_line("read", "*", "allow"))
        lines.append(_permission_line("read", "*.env", "ask"))
        lines.append(_permission_line("read", "*.env.*", "ask"))
        lines.append(_permission_line("read", "*.env.example", "allow"))
    for action in ACTION_ORDER:
        if action in actions:
            lines.append(_permission_line(action, "*", "allow"))
    lines.append(_permission_line("skill", "seo*", "allow"))
    lines.append("---")
    lines.append("")
    lines.append(GENERATED_MARKER)
    lines.append("")
    lines.append(f"You are the `{agent.id}` subagent for the claude-seo repository.")
    lines.append("")
    lines.append(f"Read `{agent.source.as_posix()}` at the repository root now and follow it as")
    lines.append("your complete role instructions. Where that file writes")
    lines.append("`${CLAUDE_PLUGIN_ROOT}`, use the repository root. Never export")
    lines.append("`${CLAUDE_PLUGIN_ROOT}`.")
    lines.append("")
    if "Bash" in agent.tools:
        lines.append("Run bundled tools as `./scripts/claude-seo run <script.py> ...` from the")
        lines.append("repository root.")
    else:
        lines.append("This role has no shell access. Use only the tools granted in your")
        lines.append("frontmatter. Do not run bundled scripts or shell commands.")
    lines.append("")
    return "\n".join(lines)


def expected_wrappers(root: Path) -> dict[str, str]:
    return {agent.id: render_wrapper(agent) for agent in discover_agents(root)}


def _wrapper_body(text: str) -> str:
    _, body = split_frontmatter(text)
    return body


def _is_generated(path: Path) -> bool:
    try:
        body = _wrapper_body(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return False
    for line in body.splitlines():
        if line.strip():
            return line.strip() == GENERATED_MARKER
    return False


def _sources(root: Path) -> list[dict[str, str]]:
    return [{"id": agent.id, "source": agent.source.as_posix()} for agent in discover_agents(root)]


def _symlink_component(path: Path, root: Path) -> Path | None:
    """Return the first symlink between root and path, if any."""
    current = path
    root = root.resolve()
    while True:
        if current.is_symlink():
            return current
        if current == root or current == current.parent:
            return None
        current = current.parent


def _result(errors: list[str], sources: list[dict[str, str]]) -> dict[str, object]:
    return {
        "written": [],
        "changed": [],
        "pruned": [],
        "missing": [],
        "stale": [],
        "errors": errors,
        "sources": sources,
    }


def check_wrappers(root: Path) -> dict[str, object]:
    """Report drift without writing. Never raises for on-disk problems."""
    root = root.resolve()
    errors: list[str] = []
    try:
        expected = expected_wrappers(root)
        sources = _sources(root)
    except ValueError as exc:
        return _result([str(exc)], [])
    for agent_id in expected:
        if not ID_RE.fullmatch(agent_id):
            errors.append(f"invalid agent id: {agent_id!r}")
    output = root / ".opencode" / "agents"
    link = _symlink_component(output, root)
    if link is not None:
        errors.append(f"refusing to use symlinked output path: {link}")
    missing: list[str] = []
    changed: list[str] = []
    stale: list[str] = []
    existing: dict[str, Path] = {}
    if output.is_dir():
        for path in sorted(output.glob("*.md")):
            if path.is_symlink():
                errors.append(f"refusing to inspect symlink: {path}")
                continue
            if not _is_generated(path):
                errors.append(f"non-generated file in output directory: {path}")
                continue
            existing[path.stem] = path
    for agent_id in expected:
        path = existing.get(agent_id)
        if path is None:
            missing.append(agent_id)
            continue
        if path.read_bytes() != expected[agent_id].encode("utf-8"):
            changed.append(agent_id)
    for agent_id in existing:
        if agent_id not in expected:
            stale.append(agent_id)
    result = _result(errors, sources)
    result["missing"] = sorted(missing)
    result["changed"] = sorted(changed)
    result["stale"] = sorted(stale)
    return result


def write_wrappers(root: Path) -> dict[str, object]:
    """Write and prune wrappers. Any validation error leaves the tree untouched."""
    root = root.resolve()
    errors: list[str] = []
    try:
        expected = expected_wrappers(root)
        sources = _sources(root)
    except ValueError as exc:
        return _result([str(exc)], [])
    for agent_id in expected:
        if not ID_RE.fullmatch(agent_id):
            errors.append(f"invalid agent id: {agent_id!r}")
    output = root / ".opencode" / "agents"
    if not output.resolve().is_relative_to(root.resolve()):
        errors.append(f"output directory escapes the repository root: {output}")
    link = _symlink_component(output, root)
    if link is not None:
        errors.append(f"refusing to use symlinked output path: {link}")
    existing: dict[str, Path] = {}
    if output.is_dir():
        for path in sorted(output.glob("*.md")):
            if path.is_symlink():
                errors.append(f"refusing to write through symlink: {path}")
                continue
            if not _is_generated(path):
                errors.append(f"non-generated file in output directory: {path}")
                continue
            existing[path.stem] = path
    if errors:
        result = _result(errors, sources)
        result["missing"] = sorted(set(expected) - set(existing))
        return result

    output.mkdir(parents=True, exist_ok=True)
    written: list[str] = []
    changed: list[str] = []
    for agent_id in sorted(expected):
        text = expected[agent_id]
        path = output / f"{agent_id}.md"
        data = text.encode("utf-8")
        if path.exists():
            if path.read_bytes() == data:
                continue
            changed.append(agent_id)
        else:
            written.append(agent_id)
        path.write_bytes(data)
    pruned: list[str] = []
    for agent_id in sorted(existing):
        if agent_id not in expected:
            existing[agent_id].unlink()
            pruned.append(agent_id)
    result = _result([], sources)
    result["written"] = written
    result["changed"] = changed
    result["pruned"] = pruned
    return result


def _print_human(result: dict[str, object], mode: str) -> None:
    print(f"mode: {mode}")
    for key in ("written", "changed", "pruned", "missing", "stale"):
        values = result[key]
        if values:
            print(f"{key}: {', '.join(values)}")
    for error in result["errors"]:
        print(f"error: {error}")
    print(f"sources: {len(result['sources'])}")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="write and prune wrappers")
    mode.add_argument("--check", action="store_true", help="report drift, exit 1")
    parser.add_argument("--json", action="store_true", help="emit machine-readable JSON")
    parser.add_argument("--root", type=Path, default=None, help="repository root override")
    args = parser.parse_args(argv)

    root = args.root if args.root is not None else Path(__file__).resolve().parents[2]
    root = root.resolve()
    result = write_wrappers(root) if args.write else check_wrappers(root)

    if args.json:
        print(json.dumps(result, indent=2, sort_keys=True))
    else:
        _print_human(result, "write" if args.write else "check")

    if result["errors"]:
        return 1
    if args.check and any(result[key] for key in ("missing", "changed", "stale")):
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
